export async function seedDemoData() {
  const existing = await storage.get('bookings');
  if (existing && existing.value) {
    try {
      const parsed = JSON.parse(existing.value);
      if (!parsed.some(b => b.id === 'bk-today-1')) {
        const merged = [...parsed, ...SEED_BOOKINGS.filter(sb => !parsed.some(p => p.id === sb.id))];
        await storage.set('bookings', JSON.stringify(merged));
      }
    } catch {}
  } else {
    await storage.set('bookings', JSON.stringify(SEED_BOOKINGS));
  }

  // Ensure facilities have multi-location fields & new sites
  const existingFacs = await storage.get('facilities');
  if (existingFacs && existingFacs.value) {
    try {
      const parsedFacs = JSON.parse(existingFacs.value);
      if (!parsedFacs[0]?.locationName || !parsedFacs.some(f => f.id === 'fac-7')) {
        const mergedFacs = SEED_FACILITIES.map(sf => {
          const found = parsedFacs.find(p => p.id === sf.id);
          return found ? { ...sf, ...found, locationName: sf.locationName, city: sf.city, address: sf.address, travelHint: sf.travelHint, areaDistrict: sf.areaDistrict, postcode: sf.postcode, coordinates: sf.coordinates } : sf;
        });
        await storage.set('facilities', JSON.stringify(mergedFacs));
      }
    } catch {}
  } else {
    await storage.set('facilities', JSON.stringify(SEED_FACILITIES));
  }

  const existingSettings = await storage.get('settings');
  if (!existingSettings || !existingSettings.value) {
    await storage.set('settings', JSON.stringify(SEED_SETTINGS));
  }

  const usersExist = await storage.get('users');
  if (!usersExist || !usersExist.value) {
    await storage.set('users', JSON.stringify(SEED_USERS));
    await storage.set('my-booking-ids', JSON.stringify(['bk-3', 'bk-4', 'bk-5']));
  }
}

export async function hashPassword(pw) {
  try {
    const enc = new TextEncoder().encode(pw);
    const buf = await window.crypto.subtle.digest('SHA-256', enc);
    return Array.from(new Uint8Array(buf)).map(b => b.toString(16).padStart(2, '0')).join('');
  } catch {
    let h = 0;
    for (let i = 0; i < pw.length; i++) h = (h * 31 + pw.charCodeAt(i)) >>> 0;
    return 'fallback' + h.toString(16);
  }
}

