// Namespaced localStorage wrapper — simulates server storage for the prototype
const PREFIX = 'sf_';

export const storage = {
  async get(key) {
    try {
      const raw = localStorage.getItem(PREFIX + key);
      return raw ? { value: raw } : null;
    } catch { return null; }
  },
  async set(key, value) {
    try { localStorage.setItem(PREFIX + key, value); }
    catch (e) { console.error('storage.set error', e); }
  },
  async remove(key) {
    try { localStorage.removeItem(PREFIX + key); }
    catch {}
  },
};

export function uid() {
  return Math.random().toString(36).slice(2, 10) + Date.now().toString(36).slice(-4);
}

function dk(offset = 0) {
  const d = new Date();
  d.setDate(d.getDate() + offset);
  return d.toISOString().slice(0, 10);
}

